//! Pure planning: validate an operation and describe exactly what will happen.

use std::path::{Path, PathBuf};

use ferriscan_core::scan::errors::ErrorCode;

use crate::protected::{ProtectedCheck, Protection, check};

/// What the user asked to do.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum ActionKind {
    /// Move each item to a destination directory.
    Move,
    /// Copy each item to a destination directory.
    Copy,
    /// Rename a single item in place.
    Rename,
    /// Send items to the OS trash.
    Trash,
    /// Delete items irreversibly.
    DeletePermanent,
}

impl ActionKind {
    /// Whether the action can be undone by replaying a journal.
    #[must_use]
    pub const fn is_reversible(self) -> bool {
        matches!(self, Self::Move | Self::Copy | Self::Rename)
    }

    /// Whether the action destroys data.
    #[must_use]
    pub const fn is_destructive(self) -> bool {
        matches!(self, Self::Trash | Self::DeletePermanent)
    }
}

/// Per-item outcome of validation.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum PlanStatus {
    /// The item will be processed.
    Ready,
    /// The item is skipped because the source is gone.
    Missing,
    /// The destination exists and needs a conflict decision.
    Conflict,
    /// The operation is refused for this item.
    Blocked,
}

/// One validated item in a plan.
#[derive(Clone, Debug)]
pub struct PlanItem {
    /// Absolute source path.
    pub source: PathBuf,
    /// Destination path, `None` for in-place deletions.
    pub destination: Option<PathBuf>,
    /// Per-item state.
    pub status: PlanStatus,
    /// Size in bytes at plan time, used for progress and free-space checks.
    pub size: u64,
    /// Why the item is not `Ready`.
    pub reason: Option<String>,
}

/// A validated, expiring description of an operation.
#[derive(Clone, Debug)]
pub struct ActionPlan {
    /// Random identifier, generated by [`plan`].
    pub id: String,
    /// Requested action.
    pub kind: ActionKind,
    /// Items in the order they will be processed.
    pub items: Vec<PlanItem>,
    /// Total bytes to move, copy or delete.
    pub total_bytes: u64,
    /// Whether the operation crosses a volume boundary.
    pub cross_volume: bool,
    /// Whether every item must be confirmed individually because it is protected.
    pub needs_override: bool,
}

impl ActionPlan {
    /// Items that will actually run.
    pub fn ready_items(&self) -> impl Iterator<Item = &PlanItem> {
        self.items.iter().filter(|i| i.status == PlanStatus::Ready)
    }

    /// Number of items that will run.
    #[must_use]
    pub fn ready_count(&self) -> usize {
        self.ready_items().count()
    }

    /// Whether the plan can run at all.
    #[must_use]
    pub fn is_executable(&self) -> bool {
        self.ready_count() > 0 && !self.needs_override
    }

    /// Whether any item needs a conflict decision.
    #[must_use]
    pub fn has_conflicts(&self) -> bool {
        self.items.iter().any(|i| i.status == PlanStatus::Conflict)
    }
}

/// Why planning failed.
#[derive(Debug, thiserror::Error)]
pub enum PlanError {
    /// No source was provided.
    #[error("no source paths")]
    Empty,
    /// The action requires a destination and none was given.
    #[error("a destination is required for {0:?}")]
    MissingDestination(ActionKind),
    /// Rename requires exactly one source.
    #[error("rename accepts exactly one source, got {0}")]
    RenameArity(usize),
    /// The destination does not exist or is not a directory.
    #[error("destination {0} is not an existing directory")]
    InvalidDestination(PathBuf),
    /// An I/O error occurred while validating.
    #[error("{code}: {message}")]
    Io {
        /// Stable code.
        code: ErrorCode,
        /// Detail.
        message: String,
    },
}

/// Validates an operation without touching the filesystem except for metadata.
///
/// # Errors
///
/// Returns [`PlanError`] when the request is structurally invalid (no source,
/// missing destination, rename with several sources, destination not a
/// directory). Per-item problems are reported in [`PlanItem::status`], not as an
/// error, so the UI can show a complete picture.
pub fn plan(
    kind: ActionKind,
    sources: &[PathBuf],
    destination: Option<&Path>,
) -> Result<ActionPlan, PlanError> {
    if sources.is_empty() {
        return Err(PlanError::Empty);
    }
    if matches!(kind, ActionKind::Move | ActionKind::Copy) && destination.is_none() {
        return Err(PlanError::MissingDestination(kind));
    }
    if kind == ActionKind::Rename && sources.len() != 1 {
        return Err(PlanError::RenameArity(sources.len()));
    }
    if let Some(dest) = destination
        && !dest.is_dir()
    {
        return Err(PlanError::InvalidDestination(dest.to_path_buf()));
    }

    let mut items = Vec::with_capacity(sources.len());
    let mut total_bytes = 0u64;
    let mut needs_override = false;
    let mut cross_volume = false;

    for source in sources {
        let mut item = PlanItem {
            source: source.clone(),
            destination: None,
            status: PlanStatus::Ready,
            size: 0,
            reason: None,
        };

        match std::fs::symlink_metadata(source) {
            Ok(meta) => {
                item.size = meta.len();
                total_bytes = total_bytes.saturating_add(item.size);
            }
            Err(err) => {
                item.status = PlanStatus::Missing;
                item.reason = Some(err.to_string());
                items.push(item);
                continue;
            }
        }

        if let ProtectedCheck::Blocked(reason) = check(source) {
            item.status = PlanStatus::Blocked;
            item.reason = Some(describe_protection(reason));
            needs_override = true;
            items.push(item);
            continue;
        }

        if let Some(dest) = destination {
            let target = dest.join(
                source
                    .file_name()
                    .ok_or_else(|| PlanError::InvalidDestination(source.clone()))?,
            );
            if target.exists() && target != *source {
                item.status = PlanStatus::Conflict;
                item.reason = Some("destination already exists".to_string());
            }
            if same_volume(source, &target) == Some(false) {
                cross_volume = true;
            }
            item.destination = Some(target);
        }

        items.push(item);
    }

    Ok(ActionPlan {
        id: new_plan_id(),
        kind,
        items,
        total_bytes,
        cross_volume,
        needs_override,
    })
}

fn describe_protection(reason: Protection) -> String {
    match reason {
        Protection::VolumeRoot => "the volume root cannot be modified".into(),
        Protection::SystemDirectory => "system directories are protected".into(),
        Protection::HomeRoot => "the home directory itself is protected".into(),
        Protection::SelfDirectory => "the application directory is protected".into(),
    }
}

/// Compares volume roots without I/O where possible.
///
/// On Windows the drive letter prefix is compared; on Unix the first two path
/// components are compared, which distinguishes `/` and `/mnt/disk` well enough
/// for a pre-flight check. The authoritative check happens at execution time.
fn same_volume(a: &Path, b: &Path) -> Option<bool> {
    #[cfg(windows)]
    {
        let ra = a.components().next()?;
        let rb = b.components().next()?;
        Some(ra.as_os_str().eq_ignore_ascii_case(rb.as_os_str()))
    }
    #[cfg(not(windows))]
    {
        let prefix = |p: &Path| -> PathBuf { p.components().take(2).collect() };
        Some(prefix(a) == prefix(b))
    }
}

fn new_plan_id() -> String {
    use std::time::{SystemTime, UNIX_EPOCH};
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_or(0, |d| d.as_nanos());
    // Not a security token: the confirm token will bind the plan (ADR-0003).
    format!("{nanos:032x}")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn temp(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join("ferriscan-plan-tests").join(name);
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).expect("mkdir");
        dir
    }

    #[test]
    fn rejects_empty_sources() {
        let err = plan(ActionKind::Move, &[], None).expect_err("must fail");
        assert!(matches!(err, PlanError::Empty));
    }

    #[test]
    fn move_requires_destination() {
        let err = plan(ActionKind::Move, &[PathBuf::from("/tmp/x")], None).expect_err("must fail");
        assert!(matches!(err, PlanError::MissingDestination(_)));
    }

    #[test]
    fn rename_accepts_one_source() {
        let dir = temp("rename");
        let file = dir.join("a.txt");
        std::fs::write(&file, b"x").expect("write");
        let err = plan(ActionKind::Rename, &[file.clone(), file], None).expect_err("must fail");
        assert!(matches!(err, PlanError::RenameArity(2)));
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn missing_source_is_reported_per_item() {
        let dir = temp("missing");
        let plan = plan(
            ActionKind::Copy,
            &[dir.join("ghost.bin")],
            Some(dir.as_path()),
        )
        .expect("plan");
        assert_eq!(plan.items[0].status, PlanStatus::Missing);
        assert!(!plan.is_executable());
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn existing_destination_is_a_conflict() {
        let dir = temp("conflict");
        let src_dir = dir.join("src");
        let dst_dir = dir.join("dst");
        std::fs::create_dir_all(&src_dir).expect("src");
        std::fs::create_dir_all(&dst_dir).expect("dst");
        let file = src_dir.join("a.txt");
        std::fs::write(&file, b"x").expect("write");
        std::fs::write(dst_dir.join("a.txt"), b"y").expect("write");

        let plan = plan(ActionKind::Copy, &[file], Some(dst_dir.as_path())).expect("plan");
        assert_eq!(plan.items[0].status, PlanStatus::Conflict);
        assert!(plan.has_conflicts());
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn totals_bytes_of_ready_items() {
        let dir = temp("sizes");
        let a = dir.join("a.bin");
        let b = dir.join("b.bin");
        std::fs::write(&a, vec![0u8; 100]).expect("write");
        std::fs::write(&b, vec![0u8; 50]).expect("write");
        let plan = plan(ActionKind::Copy, &[a, b], Some(dir.as_path())).expect("plan");
        assert_eq!(plan.total_bytes, 150);
        let _ = std::fs::remove_dir_all(&dir);
    }
}
